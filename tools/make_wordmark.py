scores={}
for ch in sorted(set("anantsec")):
    r,(ox,oy)=pole(ch); scores[ch]=(r,ox,oy)
print({k:(round(v[0],1),round(v[1]),round(v[2])) for k,v in scores.items()})

one, w1, h1 = layout(["anantsec"])
two, w2, h2 = layout(["anant","sec"])
def pick(glyphs, prefer):
    best=None
    for i,g in enumerate(glyphs):
        r,ox,oy = scores[g['ch']]
        if g['ch'] in prefer and (best is None or r>best[1]): best=(i,r,g['x']+ox,g['y']+oy)
    return best
# choose across letters present on line 0 in both layouts
cand = pick(one, set("anantsec"))
print("best letter", one[cand[0]]['ch'], "index", cand[0], "r", round(cand[1],1))
# use same glyph index in both layouts (index < 5 => on first line in the stacked layout)
idx = max(range(5), key=lambda i: scores[one[i]['ch']][0])
def pole_of(glyphs, i):
    r,ox,oy = scores[glyphs[i]['ch']]; return dict(i=i,ch=glyphs[i]['ch'],r=r,x=glyphs[i]['x']+ox,y=glyphs[i]['y']+oy)
P1=pole_of(one,idx); P2=pole_of(two,idx)
print("aperture", P1, P2)
def pack(glyphs,w,h,P):
    return dict(width=round(w,1), height=round(h,1), glyphs=[g['d'] for g in glyphs], pole=dict(x=round(P['x'],1),y=round(P['y'],1),r=round(P['r']*0.92,1),ch=P['ch']))
data=dict(single=pack(one,w1,h1,P1), stacked=pack(two,w2,h2,P2), capHeight=700, ascent=760, descent=0)
ts = "// GENERATED by tools/make_wordmark.py from Mona Sans (SIL OFL 1.1). Do not edit by hand.\n"
ts += "export const wordmark = " + json.dumps(data, indent=1) + " as const;\n"
open('src/data/wordmark.ts','w').write(ts)
print("wrote", len(ts), "bytes")
